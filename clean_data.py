import pandas as pd
import numpy as np

df = pd.read_csv('train.csv')

print("Shape:", df.shape)
df.head()

missing_count = df.isna().sum().sort_values(ascending=False)
missing_percent = (df.isna().mean() * 100).sort_values(ascending=False)

report = pd.DataFrame({
    'missing_count': missing_count,
    'missing_percent': missing_percent.round(2)
})

report.head(20)

none_cols = ['PoolQC', 'MiscFeature', 'Alley', 'Fence', 'FireplaceQu']
for col in none_cols:
    df[col] = df[col].fillna('None')

df[none_cols].isna().sum()

garage_cat = ['GarageType', 'GarageFinish', 'GarageQual', 'GarageCond']
for col in garage_cat:
    df[col] = df[col].fillna('None')
df['GarageYrBlt'] = df['GarageYrBlt'].fillna(0)

bsmt_cat = ['BsmtQual', 'BsmtCond', 'BsmtExposure', 'BsmtFinType1', 'BsmtFinType2']
for col in bsmt_cat:
    df[col] = df[col].fillna('None')

df['MasVnrType'] = df['MasVnrType'].fillna('None')

df['MasVnrArea'] = df['MasVnrArea'].fillna(0)

df['Electrical'] = df['Electrical'].fillna(df['Electrical'].mode()[0])

df['LotFrontage'] = df['LotFrontage'].fillna(df['LotFrontage'].median())

df.isna().sum().sum()

print("Duplicate rows:", df.duplicated().sum())

for c in ['GrLivArea', 'LotArea', 'TotalBsmtSF']:
    Q1 = df[c].quantile(0.25)
    Q3 = df[c].quantile(0.75)
    IQR = Q3 - Q1
    lower = Q1 - 1.5 * IQR
    upper = Q3 + 1.5 * IQR
    outliers = df[(df[c] < lower) | (df[c] > upper)]
    print(f"{c}: {len(outliers)} outliers, bounds: {lower:.1f} to {upper:.1f}")

for c in ['GrLivArea', 'LotArea', 'TotalBsmtSF']:
    print(c, "max:", df[c].max(), "min:", df[c].min())

df['MSSubClass'] = df['MSSubClass'].astype(str)

df.drop('Id', axis=1).duplicated().sum()

df['GrLivArea_outlier'] = ((df['GrLivArea'] > 4000)).astype(int)

df['MSSubClass'] = df['MSSubClass'].astype(str)

df.to_csv('clean_data.csv', index=False)